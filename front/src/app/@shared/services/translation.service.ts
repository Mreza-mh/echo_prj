  constructor() {
    // Initialize direction on load
    this.updatePageDirection(this.currentLang.value);
  }

  setLanguage(lang: string) {
    this.currentLang.next(lang);
    this.updatePageDirection(lang);
  }

  private updatePageDirection(lang: string) {
    const dir = lang === 'fa' ? 'rtl' : 'ltr';
    document.documentElement.setAttribute('dir', dir);
    document.documentElement.setAttribute('lang', lang);

    // Also update body class for theme-specific RTL adjustments if needed
    document.body.classList.remove('rtl', 'ltr');
    document.body.classList.add(dir);
  }

  getTranslation(key: string): string {
    const lang = this.currentLang.value;
    return (this.translations as any)[lang]?.[key] || key;
  }

  getCurrentLang(): string {
    return this.currentLang.value;
  }

  getDirection(): 'ltr' | 'rtl' {
    return this.currentLang.value === 'fa' ? 'rtl' : 'ltr';
  }
